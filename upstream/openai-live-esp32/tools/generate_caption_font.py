"""Regenerate the shared UI fonts from the Apache-2.0 Roboto 2.138 archive.

Normal firmware builds use the generated C files and do not need Node.js.
"""

import argparse
import hashlib
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

ARCHIVE_SHA256 = "70f64c718510a601fbcf752aafe644314dacaeb85474dc689c89787c4a72a728"
FONT_SHA256 = "b398bb9c791ddb08f1063d9c874f98e8aadb99132043b2d272a9276cf90c465a"
LICENSE_SHA256 = "c71d239df91726fc519c6eb72d318ec65820627232b2f796219e87dcf35d0ab4"
SIZES = (16, 18, 22, 28, 36)
RANGES = (
    "0x20-0x7E,0xA0-0x17F,0x2007-0x200B,0x2010-0x2015,"
    "0x2018-0x201E,0x2020-0x2022,0x2026,0x2030,0x2032-0x2033,"
    "0x2039-0x203A,0x2044,0x20AC,0x2122,0x2191,0x2193,0x2212"
)
NOTICE = """/* SPDX-License-Identifier: Apache-2.0
 * Copyright 2011 Google Inc. All Rights Reserved.
 * Modified by OpenAI: subset and rasterized from Roboto Medium 2.138 for LVGL.
 * Generated by tools/generate_caption_font.py; see README.md, LICENSE, and
 * NOTICE in this directory. Do not edit the generated tables.
 */
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--archive", required=True, type=Path,
        help="roboto-unhinted.zip from googlefonts/roboto-2 v2.138",
    )
    parser.add_argument("--converter", default="lv_font_conv")
    args = parser.parse_args()
    if hashlib.sha256(args.archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        parser.error("Roboto archive does not match the pinned v2.138 SHA-256")
    with zipfile.ZipFile(args.archive) as archive:
        font = archive.read("Roboto-Medium.ttf")
        license_text = archive.read("LICENSE")
    if hashlib.sha256(font).hexdigest() != FONT_SHA256:
        parser.error("Roboto Medium does not match the pinned SHA-256")
    if hashlib.sha256(license_text).hexdigest() != LICENSE_SHA256:
        parser.error("Roboto license does not match the pinned Apache-2.0 text")
    converter = shutil.which(args.converter)
    if not converter:
        parser.error("Install lv_font_conv@1.5.3 and pass its executable path")
    version = subprocess.check_output([converter, "--version"], text=True).strip()
    if version != "1.5.3":
        parser.error("Use lv_font_conv@1.5.3 for reproducible output")
    destination = Path(__file__).resolve().parents[1] / "examples/common/fonts"
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "Roboto-Medium.ttf").write_bytes(font)
        generated = {}
        for size in SIZES:
            name = f"live_font_{size}"
            subprocess.run(
                [
                    converter,
                    "--no-compress",
                    "--no-prefilter",
                    "--bpp",
                    "4",
                    "--size",
                    str(size),
                    "--font",
                    "Roboto-Medium.ttf",
                    "-r",
                    RANGES,
                    # Identical ink, different Unicode line-breaking semantics.
                    "-r",
                    "0x2010=>0x2011",
                    "-r",
                    "0x2009=>0x202F",
                    "--format",
                    "lvgl",
                    "--lv-include",
                    "lvgl.h",
                    "--lv-font-name",
                    name,
                    "-o",
                    f"{name}.c",
                ],
                cwd=root,
                check=True,
            )
            generated[f"{name}.c"] = (
                NOTICE + (root / f"{name}.c").read_text().rstrip() + "\n"
            )
        for name, source in generated.items():
            (destination / name).write_text(source)
        (destination / "LICENSE").write_bytes(license_text)
    print(destination)


if __name__ == "__main__":
    main()
